def test_parse_metric_takes_last_matching_line():
    output = "junk\nspeedup: 1.2\nnoise\nspeedup: 1.5\nother: 9"
    assert parse_metric(output, "speedup") == 1.5
    assert parse_metric(output, "missing") is None
    assert parse_metric("speedup: not-a-number", "speedup") is None


def test_local_optimize_end_to_end_with_fake_harness(tmp_path, monkeypatch):
    monkeypatch.chdir(tmp_path)
    (tmp_path / "value.txt").write_text("100\n", encoding="utf-8")

    calls: list[tuple[int, float | None]] = []

    def fake_harness(step: int, best: float | None) -> None:
        calls.append((step, best))
        # Each step improves the "latency" by ten.
        (tmp_path / "value.txt").write_text(f"{100 - 10 * (step + 1)}\n", encoding="utf-8")

    summary = local_optimize(
        harness_step=fake_harness,
        eval_command='echo "latency_ms: $(cat value.txt)"',
        metric="latency_ms",
        maximize=False,
        steps=3,
        workdir=tmp_path,
    )

    assert [step for step, _ in calls] == [0, 1, 2]
    assert calls[0][1] is None  # the first step sees no best yet
    assert calls[1][1] == 90.0
    assert summary["best"] == {"step": 2, "value": 70.0}
    report = json.loads((tmp_path / ".weco" / "local-loop" / "report.json").read_text(encoding="utf-8"))
    assert report["best"]["value"] == 70.0
    steps_log = (tmp_path / ".weco" / "local-loop" / "steps.jsonl").read_text(encoding="utf-8").splitlines()
    assert len(steps_log) == 3


def test_opencode_step_raises_when_harness_fails(tmp_path, monkeypatch):
    step = make_opencode_step(tmp_path, metric="m", maximize=True)

    def fake_bridge(*, prompt, agent, forwarded_args, console, stdout=None):  # noqa: ANN003
        return 3

    monkeypatch.setattr("weco.commands.start.opencode_bridge.run_opencode_bridge", fake_bridge)
    with pytest.raises(RuntimeError):
        step(0, None)
