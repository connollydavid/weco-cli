def test_container_spec_validates_name_and_command():
    with pytest.raises(ValueError):
        ContainerSpec(name="Bad Name", image="x", exec_cmd=("true",))
    with pytest.raises(ValueError):
        ContainerSpec(name="ok", image="x", exec_cmd=())


def test_install_unit_writes_under_user_quadlet_dir(tmp_path):
    path = install_unit(spec(), base=tmp_path)
    assert path == tmp_path / "weco-eval-speed.container"
    assert "[Container]" in path.read_text(encoding="utf-8")


def test_run_unit_reloads_starts_waits_and_tails_journal_on_failure(tmp_path):
    calls: list[list[str]] = []

    def fake_runner(argv, **kwargs):  # noqa: ANN003
        calls.append(list(argv))
        rc = 1 if "start" in argv else 0
        stdout = "eval crashed" if "journalctl" in argv else ""
        return SimpleNamespace(returncode=rc, stdout=stdout, stderr="")

    rc = run_unit(spec(), base=tmp_path, runner=fake_runner)
    assert rc == 1
    assert calls[0] == ["systemctl", "--user", "daemon-reload"]
    assert calls[1] == ["systemctl", "--user", "start", "--wait", unit_name(spec())]
    assert calls[2][:3] == ["journalctl", "--user", "-u"]


# ── Chroot ────────────────────────────────────────────────────────────


def manifest() -> ChrootManifest:
    return ChrootManifest(
        name="gpu-eval",
        rootfs_url="https://example/rootfs.tar.gz",
        rootfs_sha256="0" * 64,
        command=("/bin/sh", "-c", "bash /work/.weco/evaluate.sh"),
        device_binds=("/dev/nvidia0", "/dev/nvidiactl"),
    )


def make_archive(tmp_path: pathlib.Path, payload: dict[str, str]) -> pathlib.Path:
    archive = tmp_path / "rootfs.tar.gz"
    with tarfile.open(archive, "w:gz") as tar:
        for name, content in payload.items():
            data = content.encode()
            info = tarfile.TarInfo(name=name)
            info.size = len(data)
            tar.addfile(info, io.BytesIO(data))
    return archive


def test_manifest_roundtrip_and_validation():
    data = {
        "name": "gpu-eval",
        "rootfs_url": "https://example/rootfs.tar.gz",
        "rootfs_sha256": "0" * 64,
        "command": ["/bin/sh", "-c", "true"],
        "device_binds": ["/dev/nvidia0"],
    }
    parsed = ChrootManifest.from_dict(data)
    assert parsed.command == ("/bin/sh", "-c", "true")
    assert parsed.device_binds == ("/dev/nvidia0",)
    with pytest.raises(ChrootError):
        ChrootManifest.from_dict({"name": "x"})
    with pytest.raises(ChrootError):
        ChrootManifest.from_dict({**data, "command": "not-a-list"})


def test_verify_sha256_rejects_mismatch(tmp_path):
    archive = make_archive(tmp_path, {"etc/motd": "hi\n"})
    digest = hashlib.sha256(archive.read_bytes()).hexdigest()
    verify_sha256(archive, digest)
    with pytest.raises(ChrootError):
        verify_sha256(archive, "0" * 64)


def test_unpack_rejects_traversal_members(tmp_path):
    archive = tmp_path / "evil.tar"
    with tarfile.open(archive, "w") as tar:
        data = b"boom"
        info = tarfile.TarInfo(name="../escape")
        info.size = len(data)
        tar.addfile(info, io.BytesIO(data))
    with pytest.raises(ChrootError):
        unpack_rootfs(archive, tmp_path / "out")


def test_build_rootfs_is_reproducible(tmp_path):
    archive = make_archive(tmp_path, {"etc/motd": "hello\n", "bin/probe": "#!/bin/sh\n"})
    digest = hashlib.sha256(archive.read_bytes()).hexdigest()
    m = ChrootManifest(name="repro", rootfs_url="https://example/rootfs.tar.gz", rootfs_sha256=digest, command=("/bin/probe",))
    first = build_rootfs(m, archive=archive, root=tmp_path / "a")
    second = build_rootfs(m, archive=archive, root=tmp_path / "b")
    listing = lambda root: sorted(str(p.relative_to(root)) for p in root.rglob("*"))  # noqa: E731
    assert listing(first) == listing(second)
    lock_a = (tmp_path / "a" / "repro" / "manifest.lock").read_text(encoding="utf-8")
    lock_b = (tmp_path / "b" / "repro" / "manifest.lock").read_text(encoding="utf-8")
    assert lock_a == lock_b
    assert json.loads(lock_a)["rootfs_sha256"] == digest


def test_systemd_run_argv_golden(tmp_path):
    m = manifest()
    rootfs = tmp_path / "rootfs"
    workspace = tmp_path / "proj"
    argv = systemd_run_argv(m, rootfs, workspace=workspace)
